#!/usr/bin/env python3
"""Freeze a set of Python modules and emit a single C source.

Reads a JSON list of modules:
    [{"name": "json.encoder", "path": "<abs path>", "package": false}, ...]

For each entry, shells out to `_freeze_module <name> <path> <tmp.h>` to
produce a per-module header with `const unsigned char _Py_M__<mangled>[]`,
then splices every header into one generated `.c`.

Two output modes:

  --mode=full     For the canonical interpreter library (:python3). Emits
                  bootstrap_modules / stdlib_modules / test_modules and
                  assigns the global tables `_PyImport_FrozenBootstrap`
                  etc. plus the alias table.

  --mode=extras   For per-binary frozen indexes. Emits one `extras[]`
                  table and an __attribute__((constructor)) that installs
                  it into `PyImport_FrozenModules` before main(). CPython's
                  look_up_frozen() consults this pointer before the stdlib
                  table, so extras shadow / extend stdlib without
                  duplicating it.

One driver per binary scales linearly with module count and keeps the
build graph small — each python_binary creates one freeze action instead
of one per module.
"""

import argparse
import json
import os
import subprocess
import sys


BOOTSTRAP_RENAMES = {
    "importlib._bootstrap": "_frozen_importlib",
    "importlib._bootstrap_external": "_frozen_importlib_external",
    "zipimport": "zipimport",
}

ALIASES = [
    ("_frozen_importlib", "importlib._bootstrap"),
    ("_frozen_importlib_external", "importlib._bootstrap_external"),
    ("os.path", "posixpath"),
]


def varname(module_name: str) -> str:
    """Match _freeze_module.c:get_varname()."""
    return "_Py_M__" + module_name.replace(".", "_")


def c_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit_entry(name: str, var: str, is_pkg: bool) -> str:
    pkg = "true" if is_pkg else "false"
    return f"    {{{c_string(name)}, {var}, (int)sizeof({var}), {pkg}}},\n"


def freeze_one(freeze_bin: str, name: str, src: str, dst: str) -> None:
    res = subprocess.run([freeze_bin, name, src, dst], check=False)
    if res.returncode != 0:
        raise SystemExit(
            f"_freeze_module failed for {name} (rc={res.returncode})")


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--mode", required=True, choices=["full", "extras"],
                   help="Output flavor (see module docstring)")
    p.add_argument("--freeze", required=True,
                   help="Path to the _freeze_module executable")
    p.add_argument("--list", required=True,
                   help="Path to JSON list of modules to freeze")
    p.add_argument("--output", required=True,
                   help="Path to write the generated .c")
    p.add_argument("--workdir", required=True,
                   help="Directory for intermediate per-module headers")
    args = p.parse_args()

    with open(args.list) as f:
        modules = json.load(f)

    os.makedirs(args.workdir, exist_ok=True)

    headers = []
    seen: set[str] = set()
    bootstrap: list[tuple[str, str, bool]] = []
    stdlib: list[tuple[str, str, bool]] = []
    extras: list[tuple[str, str, bool]] = []

    for entry in modules:
        name = entry["name"]
        if name in seen:
            print(f"duplicate module: {name}", file=sys.stderr)
            return 1
        seen.add(name)

        var = varname(name)
        header = os.path.join(args.workdir, f"{name}.h")
        freeze_one(os.path.abspath(args.freeze), name, entry["path"], header)
        headers.append(header)

        is_pkg = bool(entry["package"])
        if args.mode == "full":
            if name in BOOTSTRAP_RENAMES:
                bootstrap.append((BOOTSTRAP_RENAMES[name], var, is_pkg))
            else:
                stdlib.append((name, var, is_pkg))
        else:  # extras
            extras.append((name, var, is_pkg))

    out: list[str] = []
    out.append("/* Auto-generated by build/gn/scripts/freeze_all_modules.py. */\n")
    out.append('#include "Python.h"\n')
    if args.mode == "full":
        out.append('#include "pycore_import.h"\n')
    out.append("#include <stdbool.h>\n\n")

    for h in sorted(headers):
        with open(h) as f:
            out.append(f.read())
        out.append("\n")

    if args.mode == "full":
        bootstrap_order = {"_frozen_importlib": 0,
                           "_frozen_importlib_external": 1,
                           "zipimport": 2}
        bootstrap.sort(key=lambda e: bootstrap_order.get(e[0], 99))
        stdlib.sort(key=lambda e: e[0])

        out.append("\nstatic const struct _frozen bootstrap_modules[] = {\n")
        for e in bootstrap:
            out.append(emit_entry(*e))
        out.append("    {0, 0, 0}\n};\n\n")

        out.append("static const struct _frozen stdlib_modules[] = {\n")
        for e in stdlib:
            out.append(emit_entry(*e))
        out.append("    {0, 0, 0}\n};\n\n")

        out.append("static const struct _frozen test_modules[] = {\n")
        out.append("    {0, 0, 0}\n};\n\n")

        out.append("const struct _frozen *_PyImport_FrozenBootstrap = bootstrap_modules;\n")
        out.append("const struct _frozen *_PyImport_FrozenStdlib = stdlib_modules;\n")
        out.append("const struct _frozen *_PyImport_FrozenTest = test_modules;\n\n")

        out.append("static const struct _module_alias aliases[] = {\n")
        for alias, orig in ALIASES:
            out.append(f"    {{{c_string(alias)}, {c_string(orig)}}},\n")
        out.append("    {0, 0}\n};\n")
        out.append("const struct _module_alias *_PyImport_FrozenAliases = aliases;\n\n")
        out.append("const struct _frozen *PyImport_FrozenModules = NULL;\n")
    else:  # extras
        extras.sort(key=lambda e: e[0])
        out.append("\nstatic const struct _frozen extras[] = {\n")
        for e in extras:
            out.append(emit_entry(*e))
        out.append("    {0, 0, 0}\n};\n\n")
        out.append("__attribute__((constructor))\n")
        out.append("static void install_extra_frozen_modules(void) {\n")
        out.append("    PyImport_FrozenModules = extras;\n")
        out.append("}\n")

    with open(args.output, "w") as f:
        f.writelines(out)

    return 0


if __name__ == "__main__":
    sys.exit(main())
