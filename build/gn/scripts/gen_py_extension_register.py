#!/usr/bin/env python3
"""Generate a C registration shim for a Python C extension module.

The shim defines a function-attribute-constructor that runs before main()
and calls PyImport_AppendInittab() to register {module_name -> init_func}
as a builtin. Because constructors fire before main(), the registration is
in place by the time Py_Initialize() is invoked inside main(). The frozen
import machinery then sees the module in `_PyImport_Inittab` and serves
`import {module_name}` without ever touching the filesystem.

This is the GN counterpart of Arcadia's `PY_REGISTER` macro
(see build/scripts/gen_py3_reg.py): one declaration per extension at the
library site, no central registry to keep in sync.
"""

import argparse


TEMPLATE = """\
/* Auto-generated by build/gn/scripts/gen_py_extension_register.py.
 * Do not edit. */

#include <Python.h>

extern PyObject* {init_func}(void);

__attribute__((constructor))
static void register_{init_func}(void) {{
    PyImport_AppendInittab("{module_name}", {init_func});
}}
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--module-name", required=True,
                        help="Dotted Python module name (e.g. 'markupsafe._speedups')")
    parser.add_argument("--init-func", required=True,
                        help="C init function name exported by the extension "
                             "(e.g. 'PyInit__speedups')")
    parser.add_argument("--output", required=True,
                        help="Path to write the generated .c file")
    args = parser.parse_args()

    with open(args.output, "w") as f:
        f.write(TEMPLATE.format(
            module_name=args.module_name,
            init_func=args.init_func,
        ))
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
