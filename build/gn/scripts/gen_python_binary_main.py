#!/usr/bin/env python3
"""Generate a C `main()` for a hermetic Python binary produced by
python_binary().

The generated main does the same isolated-config dance as
contrib/tools/python3/bin/python3_main.c (empty sys.path, site_import=0,
no environment), then hands control to runpy._run_module_as_main(<name>)
so the named frozen module runs as `__main__`. The module is resolved
through `PyImport_FrozenModules` (the per-binary override installed by
freeze_all_modules.py in extras mode), so the .py is found and executed
without any filesystem lookup.
"""

import argparse


TEMPLATE = """\
/* Auto-generated by build/gn/scripts/gen_python_binary_main.py. */

#include <Python.h>

int main(int argc, char** argv) {{
    PyConfig config;
    PyConfig_InitIsolatedConfig(&config);

    config.parse_argv = 0;
    config.site_import = 0;
    config.use_environment = 0;
    config.module_search_paths_set = 1;
    /* All stdlib and library modules are baked in as frozen modules; opt
     * into the stdlib table (the isolated config leaves only bootstrap on). */
    config.use_frozen_modules = 1;

    PyStatus status = PyConfig_SetBytesArgv(&config, argc, argv);
    if (PyStatus_Exception(status)) {{
        PyConfig_Clear(&config);
        Py_ExitStatusException(status);
    }}

    status = Py_InitializeFromConfig(&config);
    PyConfig_Clear(&config);
    if (PyStatus_Exception(status)) {{
        Py_ExitStatusException(status);
    }}

    /* Run `<main_module>` as __main__, mirroring `python -m <main_module>`.
     * runpy sets up sys.argv, __name__, __file__ etc. for the target. */
    PyObject* runpy = PyImport_ImportModule("runpy");
    if (runpy == NULL) {{
        PyErr_Print();
        return 1;
    }}
    PyObject* result = PyObject_CallMethod(
        runpy, "_run_module_as_main", "s", "{main_module}"
    );
    Py_DECREF(runpy);
    if (result == NULL) {{
        /* runpy already re-raises SystemExit's code; let Py_FinalizeEx
         * surface that via the normal exit path. */
        if (PyErr_ExceptionMatches(PyExc_SystemError)
            || !PyErr_ExceptionMatches(PyExc_SystemExit)) {{
            PyErr_Print();
        }}
        int rc = Py_FinalizeEx();
        return rc < 0 ? 1 : 1;
    }}
    Py_DECREF(result);
    return Py_FinalizeEx() < 0 ? 1 : 0;
}}
"""


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--main-module", required=True,
                        help="Name of the frozen module to run as __main__")
    parser.add_argument("--output", required=True,
                        help="Path to write the generated main.c")
    args = parser.parse_args()

    with open(args.output, "w") as f:
        f.write(TEMPLATE.format(main_module=args.main_module))
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
