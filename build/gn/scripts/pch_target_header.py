"""The precompiled header of a gn target (pch_targets of
//build/gn/pch/targets.gni) from the clang traces of a build with
time_trace = true: the headers most of its C++ files parse themselves -- not
loaded from a PCH -- written as //build/gn/pch/<dir>/<name>.h.

A header is taken when at least --share of the target's files parse it and it
is a root among those: in most of the files it is not included by another
taken header. Headers of the C++ standard library are spelled <name>,
generated ones relative to the gen dir, the rest relative to the source root;
system headers are left out.

Usage: pch_target_header.py --build-dir B [--share 0.75] //dir:name ...
"""

import argparse
import collections
import json
import os
import re
import sys

_ROOT = os.path.realpath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
_BUILD_RE = re.compile(r"^build (\S+\.o): \S*cxx ")


def objects(build_dir, label):
    d, _, name = label[2:].partition(":")
    ninja = os.path.join(build_dir, "obj", d, name + ".ninja")
    with open(ninja, encoding="utf-8") as f:
        return [m.group(1) for m in map(_BUILD_RE.match, f) if m]


def spelling(path, build_dir):
    """The include spelling of a header path of a trace, or None."""
    real = os.path.realpath(path if os.path.isabs(path) else os.path.join(build_dir, path))
    if "/libcxx/include/" in real:
        return "<%s>" % real.split("/libcxx/include/", 1)[1]
    gen = os.path.join(os.path.realpath(build_dir), "gen") + "/"
    if real.startswith(gen):
        return '"%s"' % real[len(gen):]
    root = _ROOT + "/"
    if real.startswith(root) and not real.startswith(root + "contrib/libs/cxxsupp/"):
        return '"%s"' % real[len(root):]
    return None


def headers(trace, build_dir):
    """{header spelling: (parent spelling or None, start)} of one file."""
    with open(trace, encoding="utf-8") as f:
        events = json.load(f).get("traceEvents", [])
    src = sorted(((e["ts"], 0 if e["ph"] == "e" else 1, e.get("args", {}).get("detail", ""))
                  for e in events if e.get("name") == "Source" and e.get("ph") in ("b", "e")),
                 key=lambda x: (x[0], x[1]))
    out, stack = {}, []
    for ts, begin, path in src:
        if begin:
            stack.append((ts, path))
            continue
        if not stack:
            continue
        start, path = stack.pop()
        name = spelling(path, build_dir)
        if name is None or name in out:
            continue
        parent = spelling(stack[-1][1], build_dir) if stack else None
        out[name] = (parent, start)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build-dir", required=True)
    ap.add_argument("--share", type=float, default=0.75)
    ap.add_argument("labels", nargs="+")
    args = ap.parse_args()

    for label in args.labels:
        per_file = []
        for obj in objects(args.build_dir, label):
            trace = os.path.join(args.build_dir, obj[:-len(".o")] + ".json")
            if os.path.exists(trace):
                per_file.append(headers(trace, args.build_dir))
        if not per_file:
            sys.exit("pch_target_header: no traces of %s" % label)
        n = len(per_file)
        count = collections.Counter(h for f in per_file for h in f)
        taken = {h for h, c in count.items() if c >= args.share * n}
        nested = collections.Counter(h for f in per_file for h, (parent, _) in f.items()
                                     if h in taken and parent in taken)
        roots = [h for h in taken if nested[h] < count[h] / 2]
        # in the order of the file that has most of them
        best = max(per_file, key=lambda f: sum(1 for h in roots if h in f))
        roots.sort(key=lambda h: best[h][1] if h in best else float("inf"))

        d, _, name = label[2:].partition(":")
        out = os.path.join(_ROOT, "build", "gn", "pch", d, name + ".h")
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", encoding="utf-8") as f:
            f.write("#pragma once\n\n")
            f.write("// generated by build/gn/scripts/pch_target_header.py from the clang traces\n")
            f.write("// of %s (%d files, headers parsed by >= %d%% of them)\n\n"
                    % (label, n, round(args.share * 100)))
            for h in roots:
                f.write("#include %s\n" % h)
        print("%s: %d files, %d headers -> %s" % (label, n, len(roots), os.path.relpath(out, _ROOT)))


if __name__ == "__main__":
    main()
