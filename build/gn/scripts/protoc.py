import os
import re
import shutil
import subprocess
import sys
import tempfile


OUTPUTS_DELIMITER = "--"
source_dir = os.path.abspath(sys.argv[1])


# modifies in-place all arguments that look like path
def make_absolute_path(args):
    args[:] = [os.path.relpath(os.path.abspath(arg), source_dir) if not arg.startswith('-') else arg for arg in args]


# returns outputs and splits args
def parse_outputs(args):
    del_index = args.index(OUTPUTS_DELIMITER) if OUTPUTS_DELIMITER in args else len(args)
    outputs = args[:del_index]
    make_absolute_path(outputs)
    del args[:del_index + 1]
    return outputs


# replaces `--proto-include-paths-file FILE` with `-I PATH` pairs read from FILE.
def expand_include_paths_files(args):
    result = []
    i = 0
    while i < len(args):
        if args[i] == "--proto-include-paths-file":
            with open(args[i + 1], "rt", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if line:
                        result.extend(["-I", line])
            i += 2
        else:
            result.append(args[i])
            i += 1
    return result


# protoc derives a file's canonical name (used to mangle descriptor table
# symbols) from the first `-I` whose directory is a prefix of the cmd-line
# path. The default `-I .` is a prefix of every source, so without any help
# protoc picks the long form (e.g. `contrib/libs/foo/google/api/x.proto`).
# But `import "google/api/x.proto"` from a sibling resolves through a more
# specific `-I contrib/libs/foo` and gets the short canonical name. The two
# don't match → the importer references `descriptor_table_<short>` while the
# importee defines `descriptor_table_<long>`, and link/compile fails.
#
# Fix: pass the source file in the form that matches the most specific `-I`
# it lives under. Then both direct compilation and `import` resolution agree
# on the same canonical name. Sources not inside any non-root `-I` are left
# alone (their long form via `-I .` stays consistent with itself).
#
# Returns the prefix that was stripped off (relative to `source_dir`), so the
# caller can shift `--*_out` by the same amount and keep the emitted files at
# the long path the build system expects.
def relativize_proto_sources(args, source_dir):
    includes = []
    i = 0
    while i < len(args):
        if args[i] == "-I" and i + 1 < len(args):
            includes.append(args[i + 1])
            i += 2
        else:
            i += 1
    source_dir_abs = os.path.abspath(source_dir)
    abs_includes = []
    for inc in includes:
        abs_inc = os.path.normpath(os.path.join(source_dir_abs, inc))
        # Skip the source root: it matches every file and would defeat the
        # purpose of picking the most specific `-I`.
        if abs_inc == source_dir_abs:
            continue
        abs_includes.append(abs_inc)
    abs_includes.sort(key=len, reverse=True)
    prefixes = set()
    for idx, arg in enumerate(args):
        if arg.startswith("-") or not arg.endswith(".proto"):
            continue
        abs_arg = os.path.normpath(os.path.join(source_dir_abs, arg))
        for abs_inc in abs_includes:
            inc_norm = abs_inc.rstrip("/") + "/"
            if abs_arg.startswith(inc_norm):
                args[idx] = abs_arg[len(inc_norm):]
                prefixes.add(os.path.relpath(abs_inc, source_dir_abs))
                break
    if len(prefixes) > 1:
        sys.exit("protoc.py: sources resolved against different include dirs: "
                 + ", ".join(sorted(prefixes)))
    return prefixes.pop() if prefixes else ""


# protoc derives the output path from the (possibly shortened) source name, so
# every `--*_out` directory has to be shifted by the prefix that was stripped.
def shift_output_dirs(args, prefix):
    if not prefix or prefix == ".":
        return
    i = 0
    while i < len(args):
        if args[i].startswith("--") and args[i].endswith("_out") and i + 1 < len(args):
            args[i + 1] = os.path.join(args[i + 1], prefix)
            i += 2
        else:
            i += 1


# protoc rewrites all its outputs on every run, so after any rerun (e.g. when
# protoc or one of its plugins gets relinked) everything that includes them is
# recompiled. Generate into a scratch dir instead and move over only the files
# whose content has changed: with ninja's `restat` unchanged outputs keep their
# mtime and their dependents stay up to date.
#
# Every distinct `--*_out` directory is mapped to its own scratch subdir; the
# same directory must stay the same, since plugins use insertion points into
# files generated by other plugins.
def redirect_output_dirs(args, scratch_dir):
    redirects = {}
    i = 0
    while i < len(args):
        if args[i].startswith("--") and args[i].endswith("_out") and i + 1 < len(args):
            out_dir = os.path.normpath(args[i + 1])
            if out_dir not in redirects:
                redirects[out_dir] = os.path.join(scratch_dir, str(len(redirects)))
                os.makedirs(redirects[out_dir])
            args[i + 1] = redirects[out_dir]
            i += 2
        else:
            i += 1
    return redirects


# SET(PROTOC_TRANSITIVE_HEADERS "no") of ya make (see
# build/scripts/cpp_proto_wrapper.py): protoc's proto_h makes X.proto.h, the
# messages of X with the imported ones only declared, and X.pb.h, that plus
# the imports. They become X.pb.h and X.deps.pb.h; the includes of *.proto.h
# are patched to *.pb.h (see patch_output). The plugins write into X.proto.h
# then (PROTOC_PLUGINS_LITE_HEADERS).
LITE_HEADERS_OPT = "--cpp_opt=proto_h=true"


def rename_lite_headers(redirects):
    for scratch in redirects.values():
        for root, _, files in os.walk(scratch):
            for name in files:
                if name.endswith(".pb.h") and not name.endswith((".grpc.pb.h", ".deps.pb.h")):
                    path = os.path.join(root, name)
                    os.replace(path, path[:-len(".pb.h")] + ".deps.pb.h")
            for name in files:
                if name.endswith(".proto.h"):
                    path = os.path.join(root, name)
                    os.replace(path, path[:-len(".proto.h")] + ".pb.h")


def commit_outputs(redirects, declared_outputs):
    for out_dir, scratch in redirects.items():
        for root, _, files in os.walk(scratch):
            for name in files:
                generated = os.path.join(root, name)
                target = os.path.normpath(os.path.join(out_dir, os.path.relpath(generated, scratch)))
                with open(generated, "rb") as f:
                    content = f.read()
                if target in declared_outputs:
                    patched_text, num_patches = patch_output(content.decode("utf-8"), lite)
                    if num_patches:
                        content = patched_text.encode("utf-8")
                        with open(generated, "wb") as f:
                            f.write(content)
                try:
                    with open(target, "rb") as f:
                        if f.read() == content:
                            continue
                except FileNotFoundError:
                    pass
                os.makedirs(os.path.dirname(target), exist_ok=True)
                os.replace(generated, target)


# returns patched content and number of changes.
def patch_output(content, lite=False):
    num_patches = 0
    patches = [
        (re.compile(r"((?:struct|class)\s+\S+\s+)final\s*:"), r"\1:"),
    ]
    if lite:
        patches.append((re.compile(r'(#include.*?)(\.proto\.h)"'), r'\1.pb.h"'))
    for from_re, to_re in patches:
        content, n = re.subn(from_re, to_re, content)
        num_patches += n
    return content, num_patches


# Main script
# scratch dir is in the build dir: same filesystem as outputs, so os.replace() is atomic
scratch_dir = tempfile.mkdtemp(prefix=".protoc.", dir=os.getcwd())
args = sys.argv[2:]
outputs = parse_outputs(args)
lite = LITE_HEADERS_OPT in args
args = expand_include_paths_files(args)
make_absolute_path(args)
shift_output_dirs(args, relativize_proto_sources(args, source_dir))
os.chdir(source_dir)
try:
    redirects = redirect_output_dirs(args, scratch_dir)
    env = dict(os.environ, PROTOC_PLUGINS_LITE_HEADERS="1") if lite else None
    exit = subprocess.call(args, env=env)
    if exit != 0: sys.exit(exit)
    if lite:
        rename_lite_headers(redirects)
    commit_outputs(redirects, set(os.path.normpath(output) for output in outputs))
finally:
    shutil.rmtree(scratch_dir, ignore_errors=True)

for output in outputs:
    if not os.path.exists(output):
        sys.exit("protoc.py: output was not generated: " + output)
