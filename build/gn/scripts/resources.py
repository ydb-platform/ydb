#!/usr/bin/env python3
"""Backs the resources() GN template: the counterpart of ya's RESOURCE() macro.

Usage:
    resources.py --rescompressor BIN --output OUT.cpp --data OUT.data -- ITEMS...

ITEMS use the RESOURCE() argument syntax (paths already relative to the cwd):
    PATH KEY         embed the content of the file PATH under KEY
    - KEY=VALUE      embed the string VALUE under KEY

Mirrors what ya does on Linux (build/scripts/objcopy.py):
  * every value is compressed with `rescompressor --compress-only`, i.e. with
    NResource::Compress(), exactly like ya does;
  * all compressed values are concatenated into one blob placed into the
    .rodata.__res_holder section (.lrodata.__res_holder for large blobs);
  * each key is registered at startup with NResource::LightRegisterI(key, begin, end),
    the same code `rescompiler --use-sections` generates.

The only difference is how the blob gets into the object file: ya compiles a
zero-filled placeholder and patches the section with objcopy, while here the
generated .cpp pulls the blob in with an `.incbin` directive. So the .cpp is
compiled by the regular toolchain with the library's flags (-fPIC etc.), and no
objcopy is needed.
"""

import argparse
import hashlib
import os
import subprocess
import sys
import tempfile

# Same default as --large_resource_thr in build/scripts/objcopy.py.
LARGE_RESOURCE_SIZE_MB = 64

SECTION_NAME = ".rodata.__res_holder"
LARGE_SECTION_NAME = ".lrodata.__res_holder"

# Keeps a single rescompressor command line well below the kernel limits.
MAX_BATCH_ARGS_LENGTH = 100000


def parse_items(items):
    """Returns a list of (kind, key, payload) where kind is "file" or "text"."""
    result = []
    it = iter(items)
    for item in it:
        if item == "-":
            try:
                key_value = next(it)
            except StopIteration:
                raise ValueError("'-' must be followed by KEY=VALUE")
            key, sep, value = key_value.partition("=")
            if not sep:
                raise ValueError("expected KEY=VALUE after '-', got %r" % key_value)
            result.append(("text", key, value))
        else:
            try:
                key = next(it)
            except StopIteration:
                raise ValueError("resource file %r has no key" % item)
            # rescompiler strips one leading '-' from the key of a file resource.
            if key.startswith("-"):
                key = key[1:]
            result.append(("file", key, item))
    return result


def compress(rescompressor, pairs):
    batch, length = [], 0
    for src, dst in pairs:
        batch += [src, dst]
        length += len(src) + len(dst) + 2
        if length > MAX_BATCH_ARGS_LENGTH:
            subprocess.check_call([rescompressor, "--compress-only"] + batch)
            batch, length = [], 0
    if batch:
        subprocess.check_call([rescompressor, "--compress-only"] + batch)


def c_string(text):
    out = []
    for byte in text.encode("utf-8"):
        ch = chr(byte)
        if ch in ('"', "\\"):
            out.append("\\" + ch)
        elif 0x20 <= byte < 0x7F and ch != "?":
            out.append(ch)
        else:
            out.append("\\%03o" % byte)
    return '"' + "".join(out) + '"'


def generate_cpp(entries, sizes, data_path, data_digest):
    total_size = sum(sizes)
    lines = [
        "// Generated by build/gn/scripts/resources.py, do not edit.",
        "// data: %s sha256: %s" % (data_path, data_digest),
        "",
        "// Defined in library/cpp/resource/registry.cpp",
        "namespace NResource {",
        "    int LightRegisterI(const char*, const char*, const char*);",
        "}",
        "",
    ]

    if total_size == 0:
        return "\n".join(lines) + "\n"

    holder = "R" + hashlib.sha256(data_path.encode("utf-8")).hexdigest()[:32]
    section = LARGE_SECTION_NAME if (total_size >> 20) >= LARGE_RESOURCE_SIZE_MB else SECTION_NAME
    # escaped twice: once for the assembler string, once for the C++ string literal
    incbin_path = data_path.replace("\\", "\\\\").replace('"', '\\"')

    lines += [
        "__asm__(",
        '    ".pushsection %s,\\"a%s\\",@progbits\\n"' % (section, "l" if section == LARGE_SECTION_NAME else ""),
        '    ".p2align 0\\n"',
        '    "%s:\\n"' % holder,
        '    ".incbin \\"%s\\"\\n"' % incbin_path.replace("\\", "\\\\").replace('"', '\\"'),
        '    ".popsection\\n"',
        ");",
        "",
        'extern const char %s[] __asm__("%s") __attribute__((visibility("hidden")));' % (holder, holder),
        "",
    ]

    offset = 0
    for index, ((_, key, _), size) in enumerate(zip(entries, sizes)):
        lines.append(
            "static const int REG_%d = NResource::LightRegisterI(%s, %s + %d, %s + %d);"
            % (index, c_string(key), holder, offset, holder, offset + size)
        )
        offset += size

    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--rescompressor", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--data", required=True)
    parser.add_argument("items", nargs=argparse.REMAINDER)
    args = parser.parse_args()

    items = args.items
    if items and items[0] == "--":
        items = items[1:]

    try:
        entries = parse_items(items)
    except ValueError as e:
        print("resources.py: %s" % e, file=sys.stderr)
        return 1

    rescompressor = os.path.abspath(args.rescompressor)

    out_dir = os.path.dirname(args.output)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
    data_dir = os.path.dirname(args.data)
    if data_dir:
        os.makedirs(data_dir, exist_ok=True)

    with tempfile.TemporaryDirectory(dir=data_dir or ".") as tmp:
        pairs = []
        for index, (kind, _, payload) in enumerate(entries):
            src = payload
            if kind == "text":
                src = os.path.join(tmp, "%d.txt" % index)
                with open(src, "wb") as f:
                    f.write(payload.encode("utf-8"))
            pairs.append((src, os.path.join(tmp, "%d.zst" % index)))

        compress(rescompressor, pairs)

        sizes = []
        digest = hashlib.sha256()
        with open(args.data, "wb") as blob:
            for _, compressed in pairs:
                with open(compressed, "rb") as f:
                    content = f.read()
                blob.write(content)
                digest.update(content)
                sizes.append(len(content))

    with open(args.output, "w", encoding="utf-8") as f:
        f.write(generate_cpp(entries, sizes, args.data, digest.hexdigest()))

    return 0


if __name__ == "__main__":
    sys.exit(main())
