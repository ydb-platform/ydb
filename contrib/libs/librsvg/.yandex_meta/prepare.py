"""Prepare the pinned Cargo sources and enumerate their ya build inputs."""

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tomllib


def strip_vendor():
    # Keep src, build inputs, documentation and examples: include_str! can use
    # the latter even during an ordinary library build.
    test_dirs = {
        "tests", "test", "testdata", "test_data", "fixtures", "benches",
        ".github", ".gitlab", "ci", "benchmarks", "testing-tools",
        "proptest-regressions", ".vscode", ".vim", "fuzz", "agent_docs",
    }
    windows_gnu = {"winapi-i686-pc-windows-gnu", "winapi-x86_64-pc-windows-gnu"}
    license_names = {"LICENSE", "LICENCE", "COPYING", "COPYRIGHT", "UNLICENSE"}
    for directory in sorted(Path("vendor").iterdir()):
        package = tomllib.loads((directory / "Cargo.toml").read_text())["package"]
        path = directory / ".cargo-checksum.json"
        checksums = json.loads(path.read_text())
        retained = {}
        parents = set()
        for name, checksum in checksums["files"].items():
            relative = Path(name)
            license_file = name == package.get("license-file") or bool(
                license_names.intersection(re.split(r"[._-]", relative.name.upper()))
            )
            remove = (
                relative.parts[0] in test_dirs
                or name == "Cargo.toml.orig"
                or (
                    package["name"] in windows_gnu
                    and relative.parts[0] == "lib" and relative.suffix == ".a"
                )
            )
            if remove and not license_file:
                (directory / relative).unlink()
                parents.update(directory / p for p in relative.parents if p != Path("."))
            else:
                retained[name] = checksum
        for parent in sorted(parents, key=lambda p: (len(p.parts), str(p)), reverse=True):
            if not any(parent.iterdir()):
                parent.rmdir()
        # Preserve the registry package checksum and every retained file hash.
        checksums["files"] = retained
        path.write_text(json.dumps(checksums, sort_keys=True) + "\n")


def registry_packages(path):
    lock = tomllib.loads(path.read_text())
    return {
        (package["name"], package["version"], package["source"]): package.get("checksum")
        for package in lock["package"] if "source" in package
    }


def vendor():
    cargo = os.environ.get("CARGO", "cargo")
    before = registry_packages(Path("Cargo.lock"))
    # Prune removed workspace members and test dependencies while preserving
    # every registry version/checksum from the upstream lockfile.
    subprocess.run([cargo, "update", "--workspace"], check=True)
    after = registry_packages(Path("Cargo.lock"))
    changed = {
        key: value for key, value in after.items()
        if key not in before or before[key] != value
    }
    if changed:
        raise RuntimeError("Workspace pruning changed pinned dependencies: " + repr(changed))
    Path(".cargo").mkdir(exist_ok=True)
    with Path(".cargo/config.toml").open("w") as config:
        subprocess.run([cargo, "vendor", "--locked", "vendor"], stdout=config, check=True)
    strip_vendor()
    for name in ("rsvg/tests", "librsvg-c/tests", "librsvg-c/tests-c"):
        if Path(name).is_dir():
            shutil.rmtree(name)


def output(destination):
    for name in ("Cargo.toml", "Cargo.lock", "meson.build", "build.py", "AUTHORS"):
        shutil.copy2(name, destination / name)
    for name in ("include", "rsvg", "librsvg-c", "vendor", "ut"):
        shutil.copytree(name, destination / name, dirs_exist_ok=True)
    inputs = ["Cargo.toml", "Cargo.lock", "meson.build", ".cargo/config.toml"]
    for name in ("rsvg", "librsvg-c", "vendor"):
        inputs += [
            path.relative_to(destination).as_posix()
            for path in (destination / name).rglob("*") if path.is_file()
        ]
    with (destination / ".yandex_meta/sources.inc").open("w") as include:
        include.write("# Generated by .yandex_meta/prepare.py\n\nSET(LIBRSVG_INPUTS\n")
        for name in sorted(inputs):
            include.write("    " + json.dumps(name) + "\n")
        include.write(")\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("vendor", "output"))
    parser.add_argument("destination", nargs="?", type=Path)
    args = parser.parse_args()
    if args.command == "vendor":
        vendor()
    else:
        output(args.destination)


if __name__ == "__main__":
    main()
