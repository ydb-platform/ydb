import os
import subprocess
import unittest

try:
    import yatest.common as yatest_common
except ImportError:
    yatest_common = None

from ydb.core.kqp.opt.rbo.verification.rbo_verifier import smt


SOLVER = (
    yatest_common.binary_path("contrib/tools/z3/z3")
    if yatest_common is not None
    else os.environ.get("RBO_Z3")
)


class SmtTest(unittest.TestCase):
    def test_script_is_typed_and_deterministic(self):
        script = smt.Script(timeout_ms=100)
        value = script.fresh_constant("ignored user hint", smt.INT)
        predicate = script.fresh_function("predicate", (smt.INT,), smt.BOOL)
        script.assert_(predicate(value))
        self.assertEqual(
            script.render(),
            "; Generated by the YDB new-RBO bounded equivalence verifier.\n"
            "(set-option :timeout 100)\n"
            "(set-option :produce-models true)\n"
            "(set-logic ALL)\n"
            '; v_0: "ignored user hint"\n'
            "(declare-fun v_0 () Int)\n"
            '; f_1: "predicate"\n'
            "(declare-fun f_1 (Int) Bool)\n"
            "(assert (f_1 v_0))\n"
            "(check-sat)\n",
        )

    def test_nullary_uninterpreted_function_is_a_symbol(self):
        script = smt.Script()
        function = script.fresh_function("constant", (), smt.INT)
        script.assert_(smt.eq(function(), smt.int_value(1)))
        self.assertIn("(assert (= f_0 1))", script.render())

    def test_get_value_parser(self):
        expressions = smt.parse_sexpressions('sat\n((v_0 true) (v_1 (- 3)) (v_2 "a""b"))\n')
        bindings = expressions[1]
        self.assertEqual(smt.atom_value(bindings[0][1]), True)
        self.assertEqual(smt.atom_value(bindings[1][1]), -3)
        self.assertEqual(smt.atom_value(bindings[2][1]), 'a"b')

    def test_strings_are_injective_equality_only_atoms(self):
        script = smt.Script()
        self.assertEqual(script.string_atom("é"), smt.int_value(0))
        self.assertEqual(script.string_atom("u{e9}"), smt.int_value(1))
        self.assertEqual(script.string_atom("é"), smt.int_value(0))
        self.assertEqual(script.string_literals, {0: "é", 1: "u{e9}"})

    def test_python_boolean_is_not_an_smt_boolean(self):
        with self.assertRaises(smt.SmtError):
            smt.and_(True)  # type: ignore[arg-type]

    def test_integer_modulo_is_typed_and_constant_folded(self):
        value = smt.symbol("value", smt.INT)
        self.assertEqual(smt.mod(value, 8).render(), "(mod value 8)")
        self.assertEqual(smt.mod(smt.int_value(-1), 8), smt.int_value(7))
        with self.assertRaises(smt.SmtError):
            smt.mod(value, 0)

    def test_positive_constant_integer_division_is_exact_and_typed(self):
        value = smt.symbol("value", smt.INT)
        self.assertEqual(smt.div(value, 10).render(), "(div value 10)")
        self.assertEqual(smt.div(value, 1), value)
        self.assertEqual(smt.div(smt.int_value(9), 2), smt.int_value(4))
        self.assertEqual(smt.div(smt.int_value(-9), 2), smt.int_value(-5))
        for divisor in (0, -1, True):
            with self.subTest(divisor=divisor):
                with self.assertRaises(smt.SmtError):
                    smt.div(value, divisor)
        with self.assertRaises(smt.SmtError):
            smt.div(smt.TRUE, 2)

    def test_integer_arithmetic_is_typed_and_constant_folded(self):
        left = smt.symbol("left", smt.INT)
        right = smt.symbol("right", smt.INT)
        self.assertEqual(smt.add(left, right).render(), "(+ left right)")
        self.assertEqual(smt.sub(left, right).render(), "(- left right)")
        self.assertEqual(smt.mul(left, right).render(), "(* left right)")
        self.assertEqual(smt.add(smt.int_value(3), smt.int_value(5)), smt.int_value(8))
        self.assertEqual(smt.sub(smt.int_value(3), smt.int_value(5)), smt.int_value(-2))
        self.assertEqual(smt.mul(smt.int_value(-3), smt.int_value(5)), smt.int_value(-15))
        with self.assertRaises(smt.SmtError):
            smt.add(smt.TRUE, right)
        with self.assertRaises(smt.SmtError):
            smt.sub(smt.TRUE, right)
        with self.assertRaises(smt.SmtError):
            smt.mul(left, smt.TRUE)

    def test_integer_less_than_is_typed_and_constant_folded(self):
        left = smt.symbol("left", smt.INT)
        right = smt.symbol("right", smt.INT)
        self.assertEqual(smt.lt(left, right).render(), "(< left right)")
        self.assertEqual(smt.lt(smt.int_value(1), smt.int_value(2)), smt.TRUE)
        self.assertEqual(smt.lt(left, left), smt.FALSE)
        with self.assertRaises(smt.SmtError):
            smt.lt(smt.TRUE, right)

    def test_equality_is_typed_and_constant_folded(self):
        value = smt.symbol("value", smt.INT)
        self.assertEqual(smt.eq(value, smt.int_value(1)).render(), "(= value 1)")
        self.assertEqual(smt.eq(smt.int_value(1), smt.int_value(2)), smt.FALSE)
        self.assertEqual(smt.eq(smt.FALSE, smt.TRUE), smt.FALSE)
        with self.assertRaises(smt.SmtError):
            smt.eq(smt.TRUE, value)

    def test_quantifiers_render_typed_shadowing_exactly(self):
        script = smt.Script()
        rank = script.fresh_constant("sort rank", smt.INT)
        tie = script.fresh_constant("tie choice", smt.BOOL)
        body = smt.or_(tie, smt.lt(rank, smt.int_value(2)))
        script.assert_(smt.forall((rank, tie), body))

        self.assertEqual(
            script.render(),
            "; Generated by the YDB new-RBO bounded equivalence verifier.\n"
            "(set-option :produce-models true)\n"
            "(set-logic ALL)\n"
            '; v_0: "sort rank"\n'
            "(declare-fun v_0 () Int)\n"
            '; v_1: "tie choice"\n'
            "(declare-fun v_1 () Bool)\n"
            "(assert (forall ((v_0 Int) (v_1 Bool)) (or v_1 (< v_0 2))))\n"
            "(check-sat)\n",
        )
        self.assertEqual(
            smt.exists((rank,), smt.eq(rank, smt.int_value(1))).render(),
            "(exists ((v_0 Int)) (= v_0 1))",
        )

    def test_shared_dag_renders_as_dependency_ordered_lets(self):
        left = smt.symbol("left", smt.INT)
        right = smt.symbol("right", smt.INT)
        shared_sum = smt.add(left, right)
        shared_product = smt.mul(shared_sum, shared_sum)
        term = smt.lt(shared_product, smt.add(shared_product, smt.ONE))

        self.assertEqual(
            term.render_shared(),
            "(let ((rbo_let_0 (+ left right))) "
            "(let ((rbo_let_1 (* rbo_let_0 rbo_let_0))) "
            "(< rbo_let_1 (+ rbo_let_1 1))))",
        )
        self.assertEqual(term.render_shared(), term.render_shared())

    def test_shared_quantified_body_is_not_hoisted_past_shadowing(self):
        rank = smt.symbol("rank", smt.INT)
        successor = smt.add(rank, smt.ONE)
        body = smt.lt(successor, smt.add(successor, smt.ONE))
        quantified = smt.exists((rank,), body)

        self.assertEqual(
            quantified.render_shared(),
            "(exists ((rank Int)) "
            "(let ((rbo_let_0 (+ rank 1))) "
            "(< rbo_let_0 (+ rbo_let_0 1))))",
        )

    def test_one_dag_gets_distinct_lets_across_a_shadowing_binder(self):
        rank = smt.symbol("rank", smt.INT)
        shared = smt.add(rank, smt.ONE)
        repeated = smt.lt(shared, smt.add(shared, smt.ONE))
        term = smt.and_(repeated, smt.exists((rank,), repeated))

        self.assertEqual(
            term.render_shared(),
            "(let ((rbo_let_0 (+ rank 1))) "
            "(and (< rbo_let_0 (+ rbo_let_0 1)) "
            "(exists ((rank Int)) "
            "(let ((rbo_let_1 (+ rank 1))) "
            "(< rbo_let_1 (+ rbo_let_1 1))))))",
        )

    @unittest.skipUnless(SOLVER, "run through ya or set RBO_Z3")
    def test_z3_observes_global_and_shadowed_uses_of_one_dag(self):
        script = smt.Script(timeout_ms=10_000)
        rank = script.fresh_constant("global rank", smt.INT)
        shared = smt.add(rank, smt.ONE)
        global_value = smt.eq(shared, smt.ONE)
        local_value = smt.eq(shared, smt.int_value(2))
        script.assert_(smt.and_(
            global_value,
            global_value,
            smt.exists((rank,), smt.and_(local_value, local_value)),
        ))

        solved = subprocess.run(
            (SOLVER, "-in"),
            input=script.render(),
            text=True,
            capture_output=True,
            check=False,
            timeout=15,
        )

        self.assertEqual(solved.returncode, 0, solved.stderr)
        self.assertEqual(solved.stdout.strip(), "sat")

    def test_let_aliases_are_hygienic(self):
        collision = smt.symbol("rbo_let_0", smt.INT)
        shared = smt.add(collision, smt.ONE)
        term = smt.lt(shared, smt.add(shared, smt.ONE))

        self.assertEqual(
            term.render_shared(),
            "(let ((rbo_let_1 (+ rbo_let_0 1))) "
            "(< rbo_let_1 (+ rbo_let_1 1)))",
        )

    def test_zero_variable_quantifier_is_the_body(self):
        body = smt.symbol("condition", smt.BOOL)
        self.assertIs(smt.forall((), body), body)
        self.assertIs(smt.exists((), body), body)

    def test_quantifier_rejects_invalid_or_duplicate_binders(self):
        value = smt.symbol("value", smt.INT)
        predicate = smt.Function("predicate", (smt.INT,), smt.BOOL)(value)
        invalid_sort = smt.Term("Real", "symbol", atom="real_value")
        same_name_other_sort = smt.symbol("value", smt.BOOL)

        for variables in (
            (smt.int_value(1),),
            (predicate,),
            (invalid_sort,),
            (value, value),
            (value, same_name_other_sort),
        ):
            with self.subTest(variables=variables):
                with self.assertRaises(smt.SmtError):
                    smt.forall(variables, smt.TRUE)
        with self.assertRaises(smt.SmtError):
            smt.forall((value,), smt.ONE)


if __name__ == "__main__":
    unittest.main()
