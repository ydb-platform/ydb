    def test_integer_modulo_is_typed_and_constant_folded(self):
        value = smt.symbol("value", smt.INT)
        self.assertEqual(smt.mod(value, 8).render(), "(mod value 8)")
        self.assertEqual(smt.mod(smt.int_value(-1), 8), smt.int_value(7))
        with self.assertRaises(smt.SmtError):
            smt.mod(value, 0)

    def test_positive_constant_integer_division_is_exact_and_typed(self):
        value = smt.symbol("value", smt.INT)
        self.assertEqual(smt.div(value, 10).render(), "(div value 10)")
        self.assertEqual(smt.div(value, 1), value)
        self.assertEqual(smt.div(smt.int_value(9), 2), smt.int_value(4))
        self.assertEqual(smt.div(smt.int_value(-9), 2), smt.int_value(-5))
        for divisor in (0, -1, True):
            with self.subTest(divisor=divisor):
                with self.assertRaises(smt.SmtError):
                    smt.div(value, divisor)
        with self.assertRaises(smt.SmtError):
            smt.div(smt.TRUE, 2)

    def test_nonnegative_by_positive_symbolic_division_is_narrow_and_exact(self):
        dividend = smt.symbol("dividend", smt.INT)
        divisor = smt.symbol("divisor", smt.INT)
        self.assertEqual(
            smt.div_nonnegative_by_positive(dividend, divisor).render(),
            "(div dividend divisor)",
        )
        self.assertEqual(
            smt.div_nonnegative_by_positive(smt.int_value(17), smt.int_value(5)),
            smt.int_value(3),
        )
        self.assertIs(
            smt.div_nonnegative_by_positive(dividend, smt.ONE),
            dividend,
        )
        for invalid_dividend, invalid_divisor in (
            (smt.int_value(-1), divisor),
            (dividend, smt.ZERO),
            (dividend, smt.int_value(-1)),
            (smt.TRUE, divisor),
            (dividend, smt.TRUE),
        ):
            with self.subTest(
                dividend=invalid_dividend,
                divisor=invalid_divisor,
            ):
                with self.assertRaises(smt.SmtError):
                    smt.div_nonnegative_by_positive(
                        invalid_dividend,
                        invalid_divisor,
                    )

    def test_integer_arithmetic_is_typed_and_constant_folded(self):
        left = smt.symbol("left", smt.INT)
        right = smt.symbol("right", smt.INT)
        self.assertEqual(smt.add(left, right).render(), "(+ left right)")
        self.assertEqual(smt.sub(left, right).render(), "(- left right)")
        self.assertEqual(smt.mul(left, right).render(), "(* left right)")
        self.assertEqual(smt.add(smt.int_value(3), smt.int_value(5)), smt.int_value(8))
        self.assertEqual(smt.sub(smt.int_value(3), smt.int_value(5)), smt.int_value(-2))
        self.assertEqual(smt.mul(smt.int_value(-3), smt.int_value(5)), smt.int_value(-15))
        with self.assertRaises(smt.SmtError):
            smt.add(smt.TRUE, right)
        with self.assertRaises(smt.SmtError):
            smt.sub(smt.TRUE, right)
        with self.assertRaises(smt.SmtError):
            smt.mul(left, smt.TRUE)

    def test_integer_less_than_is_typed_and_constant_folded(self):
        left = smt.symbol("left", smt.INT)
        right = smt.symbol("right", smt.INT)
        self.assertEqual(smt.lt(left, right).render(), "(< left right)")
        self.assertEqual(smt.lt(smt.int_value(1), smt.int_value(2)), smt.TRUE)
        self.assertEqual(smt.lt(left, left), smt.FALSE)
        with self.assertRaises(smt.SmtError):
            smt.lt(smt.TRUE, right)

    def test_equality_is_typed_and_constant_folded(self):
        value = smt.symbol("value", smt.INT)
        self.assertEqual(smt.eq(value, smt.int_value(1)).render(), "(= value 1)")
        self.assertEqual(smt.eq(smt.int_value(1), smt.int_value(2)), smt.FALSE)
        self.assertEqual(smt.eq(smt.FALSE, smt.TRUE), smt.FALSE)
        with self.assertRaises(smt.SmtError):
            smt.eq(smt.TRUE, value)

    def test_quantifiers_render_typed_shadowing_exactly(self):
        script = smt.Script()
        rank = script.fresh_constant("sort rank", smt.INT)
        tie = script.fresh_constant("tie choice", smt.BOOL)
        body = smt.or_(tie, smt.lt(rank, smt.int_value(2)))
        script.assert_(smt.forall((rank, tie), body))

        self.assertEqual(
            script.render(),
            "; Generated by the YDB new-RBO bounded equivalence verifier.\n"
            "(set-option :produce-models true)\n"
            "(set-logic ALL)\n"
            '; v_0: "sort rank"\n'
            "(declare-fun v_0 () Int)\n"
            '; v_1: "tie choice"\n'
            "(declare-fun v_1 () Bool)\n"
            "(assert (forall ((v_0 Int) (v_1 Bool)) (or v_1 (< v_0 2))))\n"
            "(check-sat)\n",
        )
        self.assertEqual(
            smt.exists((rank,), smt.eq(rank, smt.int_value(1))).render(),
            "(exists ((v_0 Int)) (= v_0 1))",
        )

    def test_shared_dag_renders_as_dependency_ordered_lets(self):
        left = smt.symbol("left", smt.INT)
        right = smt.symbol("right", smt.INT)
        shared_sum = smt.add(left, right)
        shared_product = smt.mul(shared_sum, shared_sum)
        term = smt.lt(shared_product, smt.add(shared_product, smt.ONE))

        self.assertEqual(
            term.render_shared(),
            "(let ((rbo_let_0 (+ left right))) "
            "(let ((rbo_let_1 (* rbo_let_0 rbo_let_0))) "
            "(< rbo_let_1 (+ rbo_let_1 1))))",
        )
        self.assertEqual(term.render_shared(), term.render_shared())

    def test_shared_quantified_body_is_not_hoisted_past_shadowing(self):
        rank = smt.symbol("rank", smt.INT)
        successor = smt.add(rank, smt.ONE)
        body = smt.lt(successor, smt.add(successor, smt.ONE))
        quantified = smt.exists((rank,), body)

        self.assertEqual(
            quantified.render_shared(),
            "(exists ((rank Int)) "
            "(let ((rbo_let_0 (+ rank 1))) "
            "(< rbo_let_0 (+ rbo_let_0 1))))",
        )

    def test_one_dag_gets_distinct_lets_across_a_shadowing_binder(self):
        rank = smt.symbol("rank", smt.INT)
        shared = smt.add(rank, smt.ONE)
        repeated = smt.lt(shared, smt.add(shared, smt.ONE))
        term = smt.and_(repeated, smt.exists((rank,), repeated))

        self.assertEqual(
            term.render_shared(),
            "(let ((rbo_let_0 (+ rank 1))) "
            "(and (< rbo_let_0 (+ rbo_let_0 1)) "
            "(exists ((rank Int)) "
            "(let ((rbo_let_1 (+ rank 1))) "
            "(< rbo_let_1 (+ rbo_let_1 1))))))",
        )

