    def test_quantifier_rejects_invalid_or_duplicate_binders(self):
        value = smt.symbol("value", smt.INT)
        predicate = smt.Function("predicate", (smt.INT,), smt.BOOL)(value)
        invalid_sort = smt.Term("Real", "symbol", atom="real_value")
        same_name_other_sort = smt.symbol("value", smt.BOOL)

        for variables in (
            (smt.int_value(1),),
            (predicate,),
            (invalid_sort,),
            (value, value),
            (value, same_name_other_sort),
        ):
            with self.subTest(variables=variables):
                with self.assertRaises(smt.SmtError):
                    smt.forall(variables, smt.TRUE)
        with self.assertRaises(smt.SmtError):
            smt.forall((value,), smt.ONE)


