#!/usr/bin/env python3
"""Generate independent CPU PyTorch FP8 references; PyTorch is not needed by CI.

Regenerate with Python and torch==2.15.0 (CPU wheel):
    python -m pip install torch==2.15.0 --index-url https://download.pytorch.org/whl/cpu
    python ydb/library/vector_distance/ut/generate_float8_torch_data.py
    python ydb/library/vector_distance/ut/generate_float8_torch_data.py --check

The C++ encoder saturates finite overflow and infinities, so its reference is
float32.clamp(-torch.finfo(dtype).max, torch.finfo(dtype).max).to(dtype).
The CSV also shows plain casts, whose overflow behavior can differ. NaNs are
compared by classification and sign; PyTorch may quiet signaling NaNs and use
different payloads. All other decoded values are compared bit for bit.
"""

import argparse
import csv
import io
from pathlib import Path
import random
import struct

import torch

FORMATS = (torch.float8_e4m3fn, torch.float8_e5m2)
DIMENSIONS = (0, 1, 2, 3, 4, 5, 7, 8, 9, 15, 16, 17, 31, 32, 33, 67, 257, 1536)
SEED = 42
RANDOM_COUNT = 4096


def float_bits(value):
    return struct.unpack("<I", struct.pack("<f", value))[0]


def from_bits(bits):
    signed = [value if value < 0x80000000 else value - 0x100000000 for value in bits]
    return torch.tensor(signed, dtype=torch.int32).view(torch.float32)


def bits_of(values):
    return [value & 0xFFFFFFFF for value in values.view(torch.int32).tolist()]


def quantize(values, dtype):
    limit = torch.finfo(dtype).max
    return values.clamp(-limit, limit).to(dtype)


def examples():
    values = [
        ("positive_zero", 0.0),
        ("negative_zero", -0.0),
        ("one", 1.0),
        ("decimal", 0.1),
        ("negative_decimal", -1.2),
        ("e4m3_min_subnormal", 2**-9),
        ("e4m3_min_normal", 2**-6),
        ("e5m2_min_subnormal", 2**-16),
        ("e5m2_min_normal", 2**-14),
        ("e4m3_zero_tie", 2**-10),
        ("e5m2_zero_tie", 2**-17),
        ("e4m3_tie", 1.0625),
        ("e5m2_tie", 1.125),
        ("e4m3_max", 448.0),
        ("e4m3_overflow_tie", 464.0),
        ("e4m3_overflow", 465.0),
        ("e5m2_max", 57344.0),
        ("e5m2_overflow_tie", 61440.0),
        ("large", 1e10),
        ("negative_large", -1e10),
        ("positive_infinity", float("inf")),
        ("negative_infinity", -float("inf")),
    ]
    result = [(name, float_bits(value)) for name, value in values]
    result.extend(
        [
            ("smallest_float32_subnormal", 0x00000001),
            ("e4m3_above_tie", float_bits(1.0625) + 1),
            ("e5m2_above_tie", float_bits(1.125) + 1),
            ("positive_quiet_nan", 0x7FC12345),
            ("negative_quiet_nan", 0xFFC12345),
            ("positive_signaling_nan", 0x7F812345),
            ("negative_signaling_nan", 0xFF812345),
        ]
    )
    return result


def encoding_inputs(decoded):
    inputs = {bits for _, bits in examples()}
    # Include every decoded encoding, with the original PyTorch NaN payloads.
    for values in decoded:
        inputs.update(bits_of(values))
        finite = values[:128][torch.isfinite(values[:128])]
        midpoints = (finite[:-1] + finite[1:]) / 2
        below = torch.nextafter(midpoints, torch.zeros_like(midpoints))
        above = torch.nextafter(midpoints, torch.full_like(midpoints, float("inf")))
        for value in bits_of(torch.cat((below, midpoints, above))):
            inputs.update((value, value | 0x80000000))
    # Sample raw FP32 bits, rather than a narrow distribution of real numbers.
    rng = random.Random(SEED)
    inputs.update(rng.getrandbits(32) for _ in range(RANDOM_COUNT))
    return sorted(inputs)


def array(name, ctype, values, width=12, render=str):
    lines = [f"inline constexpr std::array<{ctype}, {len(values)}> {name} = {{{{"]
    for offset in range(0, len(values), width):
        lines.append("    " + ", ".join(render(value) for value in values[offset : offset + width]) + ",")
    lines.extend(["}};", ""])
    return "\n".join(lines)


def render_header(decoded, inputs, raw, saturated):
    output = [
        "#pragma once",
        "",
        "// Generated by generate_float8_torch_data.py; do not edit.",
        f"// PyTorch {torch.__version__}, CPU; random seed {SEED}, {RANDOM_COUNT} raw FP32 samples.",
        "// Encoding references clamp to the finite range before casting.",
        "// NaN payloads/quiet bits are not part of cross-framework value equality.",
        "",
        "#include <util/system/types.h>",
        "#include <array>",
        "",
        "namespace NVectorDistance::NFloat8::NTorchReference {",
        "",
    ]
    output.append(array("Float32Inputs", "ui32", inputs, 8, lambda value: f"0x{value:08x}u"))
    for index, name in enumerate(("E4M3", "E5M2")):
        output.append(array(name + "Decoded", "ui32", bits_of(decoded[index]), 8, lambda value: f"0x{value:08x}u"))
        output.append(array(name + "Encoded", "ui8", saturated[index], 16, lambda value: f"0x{value:02x}"))
        output.append(array(name + "PlainCast", "ui8", raw[index], 16, lambda value: f"0x{value:02x}"))

    output.extend(
        [
            "struct TDistanceCase {",
            "    size_t Offset;",
            "    size_t Length;",
            "    double L1;",
            "    double L2Sqr;",
            "    double L2;",
            "    double LL;",
            "    double LR;",
            "    double RR;",
            "};",
            "",
        ]
    )
    rng = random.Random(SEED)
    count = sum(DIMENSIONS)
    lhs = torch.tensor([rng.uniform(-600, 600) for _ in range(count)], dtype=torch.float32)
    rhs = torch.tensor([rng.uniform(-600, 600) for _ in range(count)], dtype=torch.float32)
    # Include zero and subnormal coordinates in the vectors as well.
    lhs[::7] = 0
    rhs[::11] = 2**-9
    for dtype, name in zip(FORMATS, ("E4M3", "E5M2")):
        left = quantize(lhs, dtype)
        right = quantize(rhs, dtype)
        output.append(array(name + "Lhs", "ui8", left.view(torch.uint8).tolist(), 16, lambda value: f"0x{value:02x}"))
        output.append(array(name + "Rhs", "ui8", right.view(torch.uint8).tolist(), 16, lambda value: f"0x{value:02x}"))
        cases = []
        offset = 0
        for length in DIMENSIONS:
            # FP64 reductions give a stable reference for FP32 SIMD accumulation.
            a = left[offset : offset + length].float().double()
            b = right[offset : offset + length].float().double()
            diff = a - b
            l2sqr = (diff * diff).sum()
            values = (diff.abs().sum(), l2sqr, l2sqr.sqrt(), (a * a).sum(), (a * b).sum(), (b * b).sum())
            cases.append("{" + f"{offset}, {length}, " + ", ".join(repr(value.item()) for value in values) + "}")
            offset += length
        output.append(array(name + "Distances", "TDistanceCase", cases, 1))
    output.extend(["} // namespace NVectorDistance::NFloat8::NTorchReference", ""])
    return "\n".join(output)


def render_examples():
    output = io.StringIO(newline="")
    writer = csv.writer(output, lineterminator="\n")
    writer.writerow(
        (
            "format",
            "case",
            "float32",
            "float32_bits",
            "plain_cast_bits",
            "plain_cast_value",
            "saturated_bits",
            "saturated_value",
        )
    )
    cases = examples()
    values = from_bits([bits for _, bits in cases])
    for dtype in FORMATS:
        plain = values.to(dtype)
        saturated = quantize(values, dtype)
        for index, (name, bits) in enumerate(cases):
            writer.writerow(
                (
                    str(dtype),
                    name,
                    values[index].item(),
                    f"0x{bits:08x}",
                    f"0x{plain.view(torch.uint8)[index].item():02x}",
                    plain.float()[index].item(),
                    f"0x{saturated.view(torch.uint8)[index].item():02x}",
                    saturated.float()[index].item(),
                )
            )
    return output.getvalue()


def main():
    directory = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", type=Path, default=directory / "float8_torch_data.h")
    parser.add_argument("--examples", type=Path, default=directory / "float8_torch_examples.csv")
    parser.add_argument("--check", action="store_true", help="check reproducibility without writing files")
    args = parser.parse_args()
    torch.set_num_threads(1)
    decoded = [torch.arange(256, dtype=torch.uint8).view(dtype).float() for dtype in FORMATS]
    inputs = encoding_inputs(decoded)
    values = from_bits(inputs)
    raw = [values.to(dtype).view(torch.uint8).tolist() for dtype in FORMATS]
    saturated = [quantize(values, dtype).view(torch.uint8).tolist() for dtype in FORMATS]
    files = ((args.output, render_header(decoded, inputs, raw, saturated)), (args.examples, render_examples()))
    for path, content in files:
        if args.check:
            if not path.exists() or path.read_text() != content:
                parser.exit(1, f"Generated reference differs: {path}\n")
        else:
            path.write_text(content)
    print(
        f"PyTorch {torch.__version__}: {len(inputs)} FP32 inputs, 256 decodes and {len(DIMENSIONS)} vector pairs per format."
    )
    print("Reference files match." if args.check else "Generated reference header and example CSV.")


if __name__ == "__main__":
    main()
